// Generates shared/icons/icons.js from lucide-static: only the curated icons, as
// plain [tag, attrs] data so the browser and the server paint them the same way.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { CURATED_ICONS } from '../shared/icons/names.js';

const require = createRequire(import.meta.url);
const nodes = require('lucide-static/icon-nodes.json');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const missing = CURATED_ICONS.filter((name) => !nodes[name]);
if (missing.length > 0) throw new Error(`unknown lucide icons: ${missing.join(', ')}`);
const icons = Object.fromEntries(CURATED_ICONS.map((name) => [name, nodes[name]]));
const body = [
  '// Generated by scripts/build-icons.js from lucide-static (ISC licence). Do not edit.',
  `export const ICONS = ${JSON.stringify(icons)};`,
  'export const ICON_NAMES = Object.keys(ICONS);',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'shared', 'icons', 'icons.js'), body);
